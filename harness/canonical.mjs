// Canonical serialization + SHA-256, both ambient-free.
//
// Nothing here reaches for node:crypto, globalThis.crypto, or any host API. That is
// deliberate and it is a finding in its own right: 20-contract.md declares a digest
// ('sha256-<hex>') but declares no hash port, and neither ambient option survives I1
// (node:crypto is a module the core may not import; globalThis.crypto.subtle is ambient
// and async). A pure-JS implementation is the only option the contract leaves open, and
// this file is the evidence of what that costs.

/** Canonical form: object keys sorted, no insignificant whitespace. */
export function canonical(value) {
  if (value === null || typeof value !== 'object') return JSON.stringify(value) ?? 'null';
  if (Array.isArray(value)) return '[' + value.map(canonical).join(',') + ']';
  const keys = Object.keys(value).sort();
  return '{' + keys.map((k) => JSON.stringify(k) + ':' + canonical(value[k])).join(',') + '}';
}

